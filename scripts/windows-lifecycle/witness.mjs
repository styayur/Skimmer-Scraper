import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createWorldFixture } from '../../tests/fixtures/worldGlb.ts';
import { hash, ready, withInstalledGame } from './webview.mjs';

const [exe, out, stage, version, source, scope] = process.argv.slice(2);
const candidate = scope === 'candidate';
const original = stage === 'original';
const upgrade = stage === 'upgrade';
const rolledBack = stage === 'rollback';
const readJson = async name => JSON.parse(await readFile(path.join(out, name), 'utf8'));
const saveJson = (name, value) => writeFile(path.join(out, name), JSON.stringify(value, null, 2) + '\n');

const prefix = 'skimmer-scraper.';
const best = prefix + 'best.v2:stable:sakura:gen2:73581';
const assisted = best + ':challenge:grace5:assisted:surface-glide';
const records = {
  [prefix + 'best.v1']: '21.75', [best]: '120.5', [assisted]: '84.25',
  [prefix + 'preferences.v2']: JSON.stringify({ cameraMode: 'cockpit', visualStimulation: 'reduced', recordingHintDismissed: true }),
  [prefix + 'rules.v3']: JSON.stringify({ mode: 'free', graceSeconds: 7.5, shield: true, assisted: true }),
  [prefix + 'controls.v3']: JSON.stringify({ profile: 'classic', invertPitch: true }),
  [prefix + 'companions.v3']: JSON.stringify({ count: 1, formation: 'line' }),
  [prefix + 'journey.v3']: JSON.stringify({ fifthUnlocked: true }),
};
const memoryKey = 'skimmer.journey-memory.v1';
const fixture = createWorldFixture('arches');
const worldId = hash(fixture);
const packDir = 'public/realms/dragonspine/web';
const manifest = JSON.parse(await readFile(path.join(packDir, 'world-pack.json'), 'utf8'));
const readMemory = page => page.evaluate(key => localStorage.getItem(key), memoryKey);

async function importPilot(page, buffer) {
  await Promise.all([page.waitForNavigation({ waitUntil: 'domcontentloaded' }),
    page.locator('#desktop-settings input[type=file]').setInputFiles({ name: 'skimmer-pilot.json', mimeType: 'application/json', buffer })]);
  await ready(page);
}
const pilot = values => Buffer.from(JSON.stringify({ format: 'skimmer-pilot', schema: 1, records: values }));

async function exportPilot(page, filename, expected) {
  // Capture the exact Blob generated by the installed export button, without opening a save dialog.
  const raw = await page.evaluate(async () => {
    const click = HTMLAnchorElement.prototype.click;
    let url;
    try {
      HTMLAnchorElement.prototype.click = function () {
        if (this.download === 'skimmer-pilot.json') url = this.href;
        else click.call(this);
      };
      document.querySelector('#desktop-settings [data-save-export]').click();
    } finally { HTMLAnchorElement.prototype.click = click; }
    if (!url) throw Error('Pilot export did not produce a download');
    return (await fetch(url)).text();
  });
  const saved = JSON.parse(raw);
  assert.equal(saved.format, 'skimmer-pilot');
  assert.equal(saved.schema, 1);
  assert(!Object.hasOwn(saved.records, memoryKey));
  for (const [key, value] of Object.entries(expected)) assert.equal(saved.records[key], value, key);
  await writeFile(path.join(out, filename), raw);
  return hash(raw);
}

async function populateLibrary(page) {
  await page.keyboard.press('g');
  await page.locator('#local-world-library > summary').click();
  await page.locator('#local-world-file').setInputFiles({ name: 'lifecycle-arches.glb', mimeType: 'model/gltf-binary', buffer: fixture });
  await page.locator('#local-world-analyze').click();
  await page.locator('#local-world-apply').click();
  await page.waitForFunction(id => window.__SKIMMER_SCRAPER__.snapshot().localWorld?.manifest.id === id, worldId);
  await page.locator('#local-world-keep').evaluate(button => button.click());
  await page.waitForFunction(async id => (await window.__TAURI__.core.invoke('world_list')).some(w => w.manifest.id === id && w.keptVariant === 0), worldId);
  const token = await page.evaluate(pack => window.__TAURI__.core.invoke('pack_begin', { manifest: pack }), manifest);
  for (const file of manifest.files) {
    const tile = await readFile(path.join(packDir, file.name));
    assert.equal(hash(tile), file.sha256);
    await page.evaluate(({ token, bytes }) => window.__TAURI__.core.invoke('pack_put', Uint8Array.from(bytes).buffer,
      { headers: { 'x-pack-session': token } }), { token, bytes: [...tile] });
  }
  await page.evaluate(token => window.__TAURI__.core.invoke('pack_finish', { token }), token);
}

async function witnessState(page, expected) {
  const state = await page.evaluate(async ({ keys, worldId, packId }) => {
    const invoke = window.__TAURI__.core.invoke;
    const snapshot = window.__SKIMMER_SCRAPER__.snapshot();
    const entry = (await invoke('world_list')).find(w => w.manifest.id === worldId);
    const data = await invoke('world_read', { id: worldId, offset: 0, length: entry.manifest.bytes });
    const sha = async data => Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256', data)),
      b => b.toString(16).padStart(2, '0')).join('');
    const pack = (await invoke('pack_list')).find(p => p.id === packId);
    const tileHashes = [];
    for (const tile of pack.files) tileHashes.push(await sha(await invoke('pack_read', { id: packId, digest: tile.sha256 })));
    return { records: Object.fromEntries(keys.map(k => [k, localStorage.getItem(k)])),
      camera: snapshot.cameraMode, count: snapshot.companionSettings.count, formation: snapshot.companionSettings.formation,
      invertPitch: document.querySelector('[data-control=invertPitch]').checked, seed: snapshot.seed,
      fingerprint: snapshot.worldFingerprint, worldId: await sha(data), keptVariant: entry.keptVariant,
      pack: pack.id, packBytes: await invoke('pack_verify', { id: packId }), tileHashes };
  }, { keys: Object.keys(expected), worldId, packId: manifest.id });
  assert.deepEqual(state.records, expected);
  assert.deepEqual([state.camera, state.count, state.formation, state.invertPitch, state.seed], ['cockpit', 1, 'line', true, 73581]);
  assert.equal(state.worldId, worldId);
  assert.equal(state.keptVariant, 0);
  assert.deepEqual(state.tileHashes, manifest.files.map(f => f.sha256));
  assert.equal(state.packBytes, manifest.files.reduce((n, f) => n + f.bytes, 0));
  return state;
}

async function memorySettings(page) {
  await page.keyboard.press('f');
  for (const id of ['advanced-flight-settings', 'journey-memory-settings']) {
    const menu = page.locator('#' + id);
    if (!await menu.evaluate(e => e.open)) await menu.locator(':scope > summary').click();
  }
}

const report = { stage, version, scope, passed: false };
try {
  await withInstalledGame(exe, version, source, async (page, identity) => {
    report.identity = identity;
    if (original) {
      assert.equal(await readMemory(page), null);
      await importPilot(page, pilot(records));
      await populateLibrary(page);
      await page.locator('#local-world-builtin').evaluate(button => button.click());
      await page.waitForFunction(() => window.__SKIMMER_SCRAPER__.snapshot().localWorld === null);
    }
    const expected = { ...records };
    if (!original && !upgrade) expected[best] = '140';
    if (!original && !upgrade && !rolledBack) expected[assisted] = '96.5';
    report.before = await witnessState(page, expected);
    if (!original) {
      const prior = await readJson('original.json');
      assert.equal(report.before.fingerprint, prior.before.fingerprint);
    }
    if (upgrade) {
      assert.equal(await readMemory(page), null);
      // Reimport the original game's export over a higher best in the newer build.
      await importPilot(page, pilot({ [best]: '140' }));
      expected[best] = '140';
      await importPilot(page, await readFile(path.join(out, 'original-pilot.json')));
      if (candidate) {
        await memorySettings(page);
        await page.locator('#journey-memory-enabled').check();
        assert.equal(await page.locator('#journey-memory-share').isChecked(), false);
        await page.locator('#rules-close').click();
        await page.locator('#start-button').click();
        await page.waitForFunction(key => JSON.parse(localStorage.getItem(key))?.entries.some(e => e.event === 'visit'), memoryKey);
      } else {
        // Released 0.10 has no Journey Memory UI. Exercise only retention of the unknown key.
        await page.evaluate(key => localStorage.setItem(key, JSON.stringify({ version: 1, enabled: true, shareWithModel: false,
          retentionDays: 30, capacity: 64, entries: [{ id: '61ae809f-2b7b-4e9a-88d6-21d853889029', at: Date.now(),
            world: { realm: 'city', seed: 42, fingerprint: 123 }, event: 'visit', agent: 0, detail: 'visit' }] })), memoryKey);
      }
    }
    if (!original) {
      const raw = await readMemory(page);
      const memory = JSON.parse(raw);
      assert.equal(memory.version, 1);
      assert.equal(memory.enabled, true);
      assert.equal(memory.shareWithModel, false);
      assert(memory.entries.some(e => e.event === 'visit' && e.detail === 'visit'));
      report.journey = { provenance: candidate ? 'installed candidate run' : 'synthetic unknown-key retention',
        sha256: hash(raw), entries: memory.entries };
      if (!upgrade) {
        const prior = await readJson('upgrade.json');
        assert.equal(report.journey.sha256, prior.journey.sha256);
        if (candidate && !rolledBack) {
          await memorySettings(page);
          assert(await page.locator('#journey-memory-enabled').isChecked());
          assert.equal(await page.locator('#journey-memory-share').isChecked(), false);
          assert.equal(await page.locator('#journey-memory-entries li').count(), memory.entries.length);
        }
      }
    }
    if (rolledBack) {
      // The older installed importer must accept the newer pilot. Write a later Assisted score
      // on rollback and prove that re-upgrade reads it along with the untouched journal.
      await importPilot(page, await readFile(path.join(out, 'upgrade-pilot.json')));
      await importPilot(page, pilot({ [assisted]: '96.5' }));
      expected[assisted] = '96.5';
      assert.equal(hash(await readMemory(page)), report.journey.sha256);
    }
    report.pilotSha256 = await exportPilot(page, stage + '-pilot.json', expected);
  });
  report.passed = true;
} catch (error) {
  report.error = error.stack;
  throw error;
} finally { await saveJson(stage + '.json', report); }
