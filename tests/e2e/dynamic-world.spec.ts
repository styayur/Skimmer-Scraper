import { expect, test, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'node:fs';
import { createWorldFixture } from '../fixtures/worldGlb';

const evidence = 'evidence/v0.5/pr6-motion';
const snapshot = (page: Page) => page.evaluate(() => window.__SKIMMER_SCRAPER__!.snapshot());
const openWorld = async (page: Page) => {
  await page.keyboard.press('g');
  await expect(page.locator('#world-panel')).toBeVisible();
};

test('moves seeded architecture during close flight and resets its phase on retry', async ({ page }) => {
  test.setTimeout(150_000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/?seed=334458&gen=3');
  await page.waitForFunction(() => window.__SKIMMER_SCRAPER__?.snapshot().ready);
  const initial = await snapshot(page);
  expect(initial.dynamicStructures).toHaveLength(8);
  expect(new Set(initial.dynamicStructures.map(item => item.type)).size).toBeGreaterThanOrEqual(3);
  await page.locator('#start-button').click();
  await page.waitForFunction(() => window.__SKIMMER_SCRAPER__?.snapshot().mode === 'running');
  const flight = await page.evaluate(async () => {
    const game = window.__SKIMMER_SCRAPER__!;
    game.pause();
    const start = game.snapshot().dynamicStructures.find(item => item.id === 'moving:0:0:garden')!;
    await game.setPose({ x: start.position.x, y: start.position.y + 22, z: start.position.z + 33 }, { pitch: 0, roll: 0, yaw: 0 });
    game.resume();
    const middle = (await game.advance(0.31)).dynamicStructures.find(item => item.id === start.id)!;
    const near = await game.advance(0.31);
    game.pause();
    const end = near.dynamicStructures.find(item => item.id === start.id)!;
    const proximity = game.surface({ x: end.position.x, y: end.position.y + 8, z: end.position.z }, 10, true);
    return { start, middle, end, near, proximity };
  });
  expect(flight.near.surfaceLocked).toBe(true);
  expect(flight.near.shieldImpacts).toBe(0);
  expect(flight.near.companions.every(agent => agent.deployed && !agent.uncovered)).toBe(true);
  expect(flight.near.streaming?.dynamicBvhCount).toBe(8);
  const heights = [flight.start.position.y, flight.middle.position.y, flight.end.position.y];
  expect(Math.max(...heights) - Math.min(...heights)).toBeGreaterThan(0.2);
  expect(flight.proximity?.surfaceId).toBe(flight.end.id);
  expect(flight.proximity?.distance).toBeCloseTo(2.5, 4);
  mkdirSync(evidence, { recursive: true });
  await page.screenshot({ path: `${evidence}/floating-garden.png` });
  const retry = await page.evaluate(async () => {
    const game = window.__SKIMMER_SCRAPER__!;
    await game.retry();
    const state = game.snapshot();
    game.pause();
    return state;
  });
  const garden = retry.dynamicStructures.find(item => item.id === flight.end.id)!;
  expect(garden.position.y).toBeCloseTo(initial.dynamicStructures.find(item => item.id === garden.id)!.position.y, 8);
  expect(retry.streaming?.dynamicBvhCount).toBe(8);
  expect(errors).toEqual([]);
  writeFileSync(`${evidence}/procedural-motion.json`, JSON.stringify({ initial, flight, retry, errors }, null, 2));
});

test('imports an animated lift, previews and pauses it, then uses its moving collider during flight', async ({ page }) => {
  test.setTimeout(180_000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/?seed=334458');
  await page.waitForFunction(() => window.__SKIMMER_SCRAPER__?.snapshot().ready);
  await openWorld(page);
  await page.locator('#local-world-library > summary').click();
  await page.locator('#local-world-file').setInputFiles({
    name: 'lift.glb', mimeType: 'model/gltf-binary', buffer: createWorldFixture('animated'),
  });
  await page.locator('#local-world-analyze').click();
  await expect(page.locator('#local-world-config')).toBeVisible();
  await page.getByText('动画与运动路径', { exact: true }).click();
  await expect(page.locator('#local-world-motion-channels')).toContainText('平移');
  await page.locator('#local-world-motion-loop').uncheck();
  await page.locator('#local-world-motion-mesh').selectOption({ label: 'Lift · 刚体' });
  await page.locator('#local-world-motion-custom').check();
  await page.locator('#local-world-motion-x').fill('16');
  await page.locator('#local-world-motion-seconds').fill('2');
  await page.locator('#local-world-apply').click();
  await expect.poll(async () => (await snapshot(page)).localWorld?.manifest.name).toBe('lift');
  const loaded = await snapshot(page);
  expect(loaded.dynamicStructures).toHaveLength(1);
  const initial = loaded.dynamicStructures[0]!.position;
  await openWorld(page);
  await page.locator('#local-world-motion-preview').check();
  await expect.poll(async () => (await snapshot(page)).dynamicStructures[0]!.position.y).toBeGreaterThan(initial.y + 3);
  await page.locator('#local-world-motion-preview').uncheck();
  await page.keyboard.press('Escape');
  await page.locator('#start-button').click();
  await page.waitForFunction(() => window.__SKIMMER_SCRAPER__?.snapshot().mode === 'running');
  const movement = await page.evaluate(async () => {
    const game = window.__SKIMMER_SCRAPER__!;
    const after = await game.advance(0.52);
    const position = after.dynamicStructures[0]!.position;
    const hit = game.surface({ x: position.x, y: position.y + 7, z: position.z }, 6, true);
    return { after, hit };
  });
  expect(movement.after.dynamicStructures[0]!.position.y).toBeGreaterThan(initial.y + 12);
  expect(movement.after.dynamicStructures[0]!.position.x).toBeGreaterThan(initial.x + 6);
  expect(movement.hit?.surfaceId).toBe(loaded.dynamicStructures[0]!.id);
  expect(movement.hit?.distance).toBeCloseTo(2, 4);
  expect(movement.after.companions).toHaveLength(3);
  await openWorld(page);
  await page.locator('#local-world-motion-running').uncheck();
  const stopped = await snapshot(page);
  await page.keyboard.press('Escape');
  const stoppedLater = await page.evaluate(() => window.__SKIMMER_SCRAPER__!.advance(0.5));
  expect(stoppedLater.dynamicStructures).toEqual(stopped.dynamicStructures);
  await openWorld(page);
  await page.locator('#local-world-motion-running').check();
  await page.keyboard.press('Escape');
  const impact = await page.evaluate(async () => {
    const game = window.__SKIMMER_SCRAPER__!;
    await game.retry();
    const atStart = game.snapshot();
    game.pause();
    const start = atStart.dynamicStructures[0]!.position;
    await game.setPose({ x: start.x, y: start.y + 13, z: start.z + 3 }, { yaw: 0, pitch: -1.1, roll: 0 });
    game.resume();
    const after = await game.advance(0.22);
    game.pause();
    return { atStart, after };
  });
  expect(impact.atStart.dynamicStructures[0]!.position).toEqual(initial);
  expect(impact.after.shieldImpacts).toBeGreaterThan(0);
  expect(impact.after.dynamicStructures[0]!.position.y).toBeGreaterThan(initial.y + 5);
  await page.evaluate(async () => {
    const game = window.__SKIMMER_SCRAPER__!;
    const lift = game.snapshot().dynamicStructures[0]!.position;
    await game.setPose({ x: lift.x, y: lift.y + 13, z: lift.z + 37 }, { yaw: 0, pitch: -0.18, roll: 0 });
    await new Promise(requestAnimationFrame);
  });
  mkdirSync(evidence, { recursive: true });
  await page.screenshot({ path: `${evidence}/animated-lift.png` });
  await openWorld(page);
  await page.locator('#local-world-builtin').click();
  await expect.poll(async () => (await snapshot(page)).localWorld).toBeNull();
  const restored = await snapshot(page);
  expect(restored.worldReleases.at(-1)).toMatchObject({ dynamicBvhBefore: 1, dynamicBvhAfter: 0, bvhAfter: 0 });
  await page.reload();
  await page.waitForFunction(() => window.__SKIMMER_SCRAPER__?.snapshot().ready);
  await openWorld(page);
  await page.locator('#local-world-library > summary').click();
  await page.locator('#local-world-load').click();
  await expect(page.locator('#local-world-config')).toBeVisible();
  await page.getByText('动画与运动路径', { exact: true }).click();
  expect(await page.locator('#local-world-motion-loop').isChecked()).toBe(false);
  await page.locator('#local-world-motion-mesh').selectOption({ label: 'Lift · 刚体' });
  await expect(page.locator('#local-world-motion-x')).toHaveValue('16');
  expect(errors).toEqual([]);
  writeFileSync(`${evidence}/glb-motion.json`, JSON.stringify({ loaded, movement, stopped, stoppedLater, impact, restored, errors }, null, 2));
});
